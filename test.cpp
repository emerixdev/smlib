#include "smlib.h"

#include <cassert>
#include <cmath>
#include <iostream>
#include <limits>
#include <sstream>
#include <stdexcept>

using namespace smlib;

int main() {
  using vec3 = mvec<double, 3>;
  using vec4 = mvec<double, 4>;

  // ============================================================
  // Constructors
  // ============================================================

  {
    // Default constructor
    vec3 a;
    assert(a[0] == 0.0);
    assert(a[1] == 0.0);
    assert(a[2] == 0.0);

    // Fill constructor
    vec3 b(5.0);
    assert(b == vec3{5.0, 5.0, 5.0});

    // Variadic constructor
    vec3 c(1.0, 2.0, 3.0);
    assert(c[0] == 1.0);
    assert(c[1] == 2.0);
    assert(c[2] == 3.0);

    // 4D constructor
    vec4 d(1.0, 2.0, 3.0, 4.0);
    assert(d == vec4{1.0, 2.0, 3.0, 4.0});
  }

  // ============================================================
  // data()
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};

    double *p = a.data();

    assert(p != nullptr);
    assert(p[0] == 1.0);
    assert(p[1] == 2.0);
    assert(p[2] == 3.0);

    p[0] = 10.0;

    assert(a[0] == 10.0);

    const vec3 b{4.0, 5.0, 6.0};
    const double *cp = b.data();

    assert(cp[0] == 4.0);
    assert(cp[1] == 5.0);
    assert(cp[2] == 6.0);
  }

  // ============================================================
  // operator[]
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};

    assert(a[0] == 1.0);
    assert(a[1] == 2.0);
    assert(a[2] == 3.0);

    a[1] = 20.0;

    assert(a[1] == 20.0);

    const vec3 b{4.0, 5.0, 6.0};

    assert(b[0] == 4.0);
    assert(b[1] == 5.0);
    assert(b[2] == 6.0);
  }

  // ============================================================
  // operator at()
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};

    assert(a.at(0) == 1.0);
    assert(a.at(1) == 2.0);
    assert(a.at(2) == 3.0);

    a.at(1) = 20.0;

    assert(a.at(1) == 20.0);

    const vec3 b{4.0, 5.0, 6.0};

    assert(b.at(0) == 4.0);

    bool threw = false;

    try {
      a.at(3);
    } catch (const std::out_of_range &) {
      threw = true;
    }

    assert(threw);
  }

  // ============================================================
  // size()
  // ============================================================

  {
    vec3 a;
    vec4 b;

    assert(a.size() == 3);
    assert(b.size() == 4);
  }

  // ============================================================
  // fill()
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};

    a.fill(7.0);

    assert(a == vec3{7.0, 7.0, 7.0});
  }

  // ============================================================
  // x(), y(), z(), w()
  // ============================================================

  {
    vec4 a{1.0, 2.0, 3.0, 4.0};

    assert(a.x() == 1.0);
    assert(a.y() == 2.0);
    assert(a.z() == 3.0);
    assert(a.w() == 4.0);

    a.x() = 10.0;
    a.y() = 20.0;
    a.z() = 30.0;
    a.w() = 40.0;

    assert(a == vec4{10.0, 20.0, 30.0, 40.0});

    const vec4 b{5.0, 6.0, 7.0, 8.0};

    assert(b.x() == 5.0);
    assert(b.y() == 6.0);
    assert(b.z() == 7.0);
    assert(b.w() == 8.0);
  }

  // ============================================================
  // Iterators
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};

    double sum = 0.0;

    for (auto it = a.begin(); it != a.end(); ++it)
      sum += *it;

    assert(sum == 6.0);

    const vec3 b{4.0, 5.0, 6.0};

    sum = 0.0;

    for (auto it = b.cbegin(); it != b.cend(); ++it)
      sum += *it;

    assert(sum == 15.0);

    // Range-for / begin/end
    sum = 0.0;

    for (double x : a)
      sum += x;

    assert(sum == 6.0);

    // Reverse iterators
    auto rit = a.rbegin();

    assert(*rit == 3.0);
    ++rit;
    assert(*rit == 2.0);
    ++rit;
    assert(*rit == 1.0);

    // Const reverse iterators
    const auto &ca = a;

    auto crit = ca.crbegin();

    assert(*crit == 3.0);
  }

  // ============================================================
  // +=
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};
    vec3 b{4.0, 5.0, 6.0};

    a += b;

    assert(a == vec3{5.0, 7.0, 9.0});
  }

  // ============================================================
  // -=
  // ============================================================

  {
    vec3 a{5.0, 7.0, 9.0};
    vec3 b{1.0, 2.0, 3.0};

    a -= b;

    assert(a == vec3{4.0, 5.0, 6.0});
  }

  // ============================================================
  // *=
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};

    a *= 2.0;

    assert(a == vec3{2.0, 4.0, 6.0});
  }

  // ============================================================
  // /=
  // ============================================================

  {
    vec3 a{2.0, 4.0, 6.0};

    a /= 2.0;

    assert(a == vec3{1.0, 2.0, 3.0});
  }

  // ============================================================
  // operator+
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};
    vec3 b{4.0, 5.0, 6.0};

    vec3 c = a + b;

    assert(c == vec3{5.0, 7.0, 9.0});
  }

  // ============================================================
  // operator-
  // ============================================================

  {
    vec3 a{5.0, 7.0, 9.0};
    vec3 b{1.0, 2.0, 3.0};

    vec3 c = a - b;

    assert(c == vec3{4.0, 5.0, 6.0});
  }

  // ============================================================
  // vector * scalar
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};

    vec3 b = a * 2.0;

    assert(b == vec3{2.0, 4.0, 6.0});
  }

  // ============================================================
  // vector / scalar
  // ============================================================

  {
    vec3 a{2.0, 4.0, 6.0};

    vec3 b = a / 2.0;

    assert(b == vec3{1.0, 2.0, 3.0});
  }

  // ============================================================
  // unary +
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};

    assert(+a == a);
  }

  // ============================================================
  // unary -
  // ============================================================

  {
    vec3 a{1.0, -2.0, 3.0};

    assert(-a == vec3{-1.0, 2.0, -3.0});
  }

  // ============================================================
  // scalar * vector
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};

    vec3 b = 2.0 * a;

    assert(b == vec3{2.0, 4.0, 6.0});
  }

  // ============================================================
  // == / !=
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};
    vec3 b{1.0, 2.0, 3.0};
    vec3 c{1.0, 2.0, 4.0};

    assert(a == b);
    assert(!(a != b));

    assert(a != c);
    assert(!(a == c));
  }

  // ============================================================
  // dot()
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};
    vec3 b{4.0, 5.0, 6.0};

    assert(a.dot(b) == 32.0);
    assert(dot(a, b) == 32.0);
  }

  // ============================================================
  // magnitude()
  // ============================================================

  {
    vec3 a{3.0, 4.0, 0.0};

    assert(a.magnitude() == 5.0);

    vec3 b{1.0, 2.0, 2.0};

    assert(b.magnitude() == 3.0);
  }

  // ============================================================
  // magnitude_squared()
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};

    assert(a.magnitude_squared() == 14.0);
  }

  // ============================================================
  // sum()
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};

    assert(a.sum() == 6.0);
    assert(sum(a) == 6.0);
  }

  // ============================================================
  // min()
  // ============================================================

  {
    vec3 a{5.0, 2.0, 8.0};

    assert(a.min() == 2.0);
    assert(min(a) == 2.0);
  }

  // ============================================================
  // max()
  // ============================================================

  {
    vec3 a{5.0, 2.0, 8.0};

    assert(a.max() == 8.0);
    assert(max(a) == 8.0);
  }

  // ============================================================
  // unit()
  // ============================================================

  {
    vec3 a{3.0, 4.0, 0.0};

    vec3 b = a.unit();

    assert(std::abs(b.x() - 0.6) < 1e-12);
    assert(std::abs(b.y() - 0.8) < 1e-12);
    assert(std::abs(b.z()) < 1e-12);

    assert(std::abs(b.magnitude() - 1.0) < 1e-12);
  }

  // unit() should reject zero vector
  {
    vec3 a{0.0, 0.0, 0.0};

    bool threw = false;

    try {
      a.unit();
    } catch (const std::domain_error &) {
      threw = true;
    }

    assert(threw);
  }

  // ============================================================
  // normalize()
  // ============================================================

  {
    vec3 a{3.0, 4.0, 0.0};

    a.normalize();

    assert(std::abs(a.x() - 0.6) < 1e-12);
    assert(std::abs(a.y() - 0.8) < 1e-12);
    assert(std::abs(a.magnitude() - 1.0) < 1e-12);
  }

  // ============================================================
  // cross()
  // ============================================================

  {
    vec3 x{1.0, 0.0, 0.0};
    vec3 y{0.0, 1.0, 0.0};

    vec3 z = x.cross(y);

    assert(z == vec3{0.0, 0.0, 1.0});

    // Free function
    assert(cross(x, y) == vec3{0.0, 0.0, 1.0});

    // Reverse order
    assert(cross(y, x) == vec3{0.0, 0.0, -1.0});
  }

  // ============================================================
  // abs()
  // ============================================================

  {
    vec3 a{-1.0, 2.0, -3.0};

    assert(a.abs() == vec3{1.0, 2.0, 3.0});
    assert(abs(a) == vec3{1.0, 2.0, 3.0});
  }

  // ============================================================
  // floor()
  // ============================================================

  {
    vec3 a{1.9, -2.1, 3.5};

    assert(a.floor() == vec3{1.0, -3.0, 3.0});
    assert(floor(a) == vec3{1.0, -3.0, 3.0});
  }

  // ============================================================
  // ceil()
  // ============================================================

  {
    vec3 a{1.1, -2.9, 3.1};

    assert(a.ceil() == vec3{2.0, -2.0, 4.0});
    assert(ceil(a) == vec3{2.0, -2.0, 4.0});
  }

  // ============================================================
  // round()
  // ============================================================

  {
    vec3 a{1.4, 2.6, -3.4};

    assert(a.round() == vec3{1.0, 3.0, -3.0});
    assert(round(a) == vec3{1.0, 3.0, -3.0});
  }

  // ============================================================
  // sqrt()
  // ============================================================

  {
    vec3 a{1.0, 4.0, 9.0};

    assert(a.sqrt() == vec3{1.0, 2.0, 3.0});
    assert(sqrt(a) == vec3{1.0, 2.0, 3.0});
  }

  // ============================================================
  // approx_equal()
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};
    vec3 b{1.0001, 2.0001, 3.0001};

    assert(a.approx_equal(b, 0.001));
    assert(approx_equal(a, b, 0.001));

    assert(!a.approx_equal(b, 0.00001));
    assert(!approx_equal(a, b, 0.00001));

    // Exact equality
    assert(a.approx_equal(a, 0.0));

    // Negative epsilon should throw
    bool threw = false;

    try {
      a.approx_equal(b, -0.001);
    } catch (const std::invalid_argument &) {
      threw = true;
    }

    assert(threw);
  }

  // ============================================================
  // has_nan()
  // ============================================================

  {
    const double nan = std::numeric_limits<double>::quiet_NaN();

    vec3 a{1.0, 2.0, 3.0};
    vec3 b{1.0, nan, 3.0};

    assert(!a.has_nan());
    assert(b.has_nan());

    assert(!has_nan(a));
    assert(has_nan(b));
  }

  // ============================================================
  // has_infinity()
  // ============================================================

  {
    const double inf = std::numeric_limits<double>::infinity();

    vec3 a{1.0, 2.0, 3.0};
    vec3 b{1.0, inf, 3.0};

    assert(!a.has_infinity());
    assert(b.has_infinity());

    assert(!has_infinity(a));
    assert(has_infinity(b));
  }

  // ============================================================
  // is_finite()
  // ============================================================

  {
    const double inf = std::numeric_limits<double>::infinity();
    const double nan = std::numeric_limits<double>::quiet_NaN();

    vec3 a{1.0, 2.0, 3.0};
    vec3 b{1.0, inf, 3.0};
    vec3 c{1.0, nan, 3.0};

    assert(a.is_finite());
    assert(!b.is_finite());
    assert(!c.is_finite());

    assert(is_finite(a));
    assert(!is_finite(b));
    assert(!is_finite(c));
  }

  // ============================================================
  // is_zero()
  // ============================================================

  {
    vec3 a{0.0, 0.0, 0.0};
    vec3 b{0.0, 1.0, 0.0};

    assert(a.is_zero());
    assert(!b.is_zero());

    assert(is_zero(a));
    assert(!is_zero(b));
  }

  // ============================================================
  // is_near_zero()
  // ============================================================

  {
    vec3 a{0.001, -0.002, 0.0005};

    assert(a.is_near_zero(0.01));
    assert(is_near_zero(a, 0.01));

    assert(!a.is_near_zero(0.001));

    // Negative epsilon should throw
    bool threw = false;

    try {
      a.is_near_zero(-0.001);
    } catch (const std::invalid_argument &) {
      threw = true;
    }

    assert(threw);
  }

  // ============================================================
  // Scalar is_nan()
  // ============================================================

  {
    const double nan = std::numeric_limits<double>::quiet_NaN();

    assert(is_nan(nan));
    assert(!is_nan(1.0));
  }

  // ============================================================
  // Scalar is_infinite()
  // ============================================================

  {
    const double inf = std::numeric_limits<double>::infinity();

    assert(is_infinite(inf));
    assert(!is_infinite(1.0));
  }

  // ============================================================
  // Scalar is_finite()
  // ============================================================

  {
    const double inf = std::numeric_limits<double>::infinity();
    const double nan = std::numeric_limits<double>::quiet_NaN();

    assert(is_finite(1.0));
    assert(!is_finite(inf));
    assert(!is_finite(nan));
  }

  // ============================================================
  // ostream <<
  // ============================================================

  {
    vec3 a{1.0, 2.0, 3.0};

    std::ostringstream out;
    out << a;

    assert(out.str() == "{1, 2, 3}");
  }

  // ============================================================
  // constexpr tests
  // ============================================================

  {
    constexpr vec3 a{1.0, 2.0, 3.0};
    constexpr vec3 b{4.0, 5.0, 6.0};

    constexpr vec3 c = a + b;

    static_assert(c[0] == 5.0);
    static_assert(c[1] == 7.0);
    static_assert(c[2] == 9.0);

    static_assert(a.dot(b) == 32.0);
    static_assert(a.sum() == 6.0);
    static_assert(a.min() == 1.0);
    static_assert(a.max() == 3.0);
    static_assert(a.magnitude_squared() == 14.0);

    static_assert(!a.is_zero());

    constexpr vec3 x{1.0, 0.0, 0.0};
    constexpr vec3 y{0.0, 1.0, 0.0};

    constexpr vec3 z = x.cross(y);

    static_assert(z == vec3{0.0, 0.0, 1.0});
  }

  // ============================================================
  // Final message
  // ============================================================

  std::cout << "All tests passed!\n";

  return 0;
}
